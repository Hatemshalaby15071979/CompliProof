def log(msg: str) -> None:
    print(f"[remediate] {msg}")


def fail(msg: str) -> None:
    print(f"[remediate] FAIL: {msg}")
    raise SystemExit(1)


def add_license() -> None:
    if LICENSE.exists():
        log("LICENSE already exists — skipping")
        return
    LICENSE.write_text(MIT_LICENSE, encoding="utf-8")
    log("Created LICENSE (MIT)")


def add_lockfile() -> None:
    if LOCKFILE.exists():
        log("requirements.lock.txt already exists — skipping")
        return
    # Read declared runtime dependencies from pyproject.toml and write the lockfile.
    deps: list[str] = []
    try:
        import tomllib

        pyproject = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
        deps = list(pyproject.get("project", {}).get("dependencies", []))
    except Exception:
        pass
    lines = [
        "# CompliProof dependency lockfile",
        "# Generated by scripts/remediate.py --lockfile",
        "#",
        "# Runtime dependencies declared in pyproject.toml:",
    ]
    if deps:
        lines.extend(deps)
    else:
        lines.append("# (none declared)")
    lines.append("# Pin any added dependency here before shipping.")
    LOCKFILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    log(f"Created requirements.lock.txt ({len(deps)} dependency/deps)")


def fix_docker_bind() -> None:
    if not DOCKERFILE.exists():
        fail(f"docker/Dockerfile not found at {DOCKERFILE}")
    text = DOCKERFILE.read_text(encoding="utf-8")
    original = text
    # Replace the CMD bind address from 0.0.0.0 to 127.0.0.1 (loopback default).
    text = text.replace('--host", "0.0.0.0"', '--host", "127.0.0.1"')
    text = text.replace("--host 0.0.0.0", "--host 127.0.0.1")
    if text != original:
        DOCKERFILE.write_text(text, encoding="utf-8")
        log("Fixed docker/Dockerfile bind address -> 127.0.0.1")
    else:
        log("docker/Dockerfile already binds loopback — no change")


def run_tests() -> bool:
    log("Running pytest test suite")
    result = subprocess.run(
        [sys.executable, "-m", "pytest", "tests", "-q"],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    print(result.stdout)
    if result.stderr:
        print(result.stderr)
    return result.returncode == 0


def build_and_verify_wheel() -> bool:
    log("Building wheel and verifying non-empty + installable")

    # Try `python -m build` first; fall back to `pip wheel` if `build` isn't installed.
    wheel_path = _try_build_module()
    if wheel_path is None:
        wheel_path = _try_pip_wheel()
    if wheel_path is None:
        fail("Could not build a wheel (tried `python -m build` and `pip wheel`)")

    whl = Path(wheel_path)
    log(f"Wheel: {whl.name}")

    # Verify non-empty: contains compliproof modules
    with zipfile.ZipFile(whl) as z:
        mods = [n for n in z.namelist() if n.startswith("compliproof/") and n.endswith(".py")]
    if not mods:
        fail("Wheel contains no compliproof modules (empty wheel)")
    log(f"Wheel contains {len(mods)} compliproof modules")

    # Verify installable in a clean venv
    venv = Path(tempfile.mkdtemp(prefix="cp-venv-")) / "venv"
    subprocess.run([sys.executable, "-m", "venv", str(venv)], check=True)
    pip = venv / "bin" / "pip"
    subprocess.run([str(pip), "install", "--upgrade", "pip"], check=True, capture_output=True)
    install = subprocess.run([str(pip), "install", str(whl)], capture_output=True, text=True)
    print(install.stdout)
    if install.stderr:
        print(install.stderr)
    if install.returncode != 0:
        fail("pip install of wheel failed in clean venv")

    # CLI smoke test
    compliproof = venv / "bin" / "compliproof"
    server = venv / "bin" / "compliproof-server"
    for cmd in ([str(compliproof), "--help"], [str(server), "--help"]):
        r = subprocess.run(cmd, capture_output=True, text=True)
        print(r.stdout)
        if r.returncode != 0:
            print(r.stderr)
            fail(f"CLI smoke test failed: {' '.join(cmd)}")
    log("CLI smoke tests passed (compliproof --help, compliproof-server --help)")
    return True


def _try_build_module() -> str | None:
    """Attempt `python -m build --wheel --no-isolation`; return wheel path or None."""
    result = subprocess.run(
        [sys.executable, "-m", "build", "--wheel", "--no-isolation"],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    print(result.stdout)
    if result.stderr:
        print(result.stderr)
    if result.returncode != 0:
        log("`python -m build` unavailable or failed; will try pip wheel")
        return None
    whls = sorted((ROOT / "dist").glob("*.whl"))
    return str(whls[-1]) if whls else None


def _try_pip_wheel() -> str | None:
    """Attempt `pip wheel . --no-deps --no-build-isolation`; return wheel path or None."""
    outdir = ROOT / "dist"
    outdir.mkdir(parents=True, exist_ok=True)
    result = subprocess.run(
        [sys.executable, "-m", "pip", "wheel", ".", "--no-deps", "--no-build-isolation",
         "-w", str(outdir)],
        capture_output=True,
        text=True,
    )
    print(result.stdout)
    if result.stderr:
        print(result.stderr)
    if result.returncode != 0:
        log("`pip wheel` also failed")
        return None
    whls = sorted(outdir.glob("*.whl"))
    return str(whls[-1]) if whls else None


def main() -> None:
    parser = argparse.ArgumentParser(description="CompliProof remediation automation")
    parser.add_argument("--license", action="store_true")
    parser.add_argument("--lockfile", action="store_true")
    parser.add_argument("--docker-bind", action="store_true")
    parser.add_argument("--tests", action="store_true")
    parser.add_argument("--wheel", action="store_true")
    parser.add_argument("--all", action="store_true")
    args = parser.parse_args()

    if args.all:
        args.license = args.lockfile = args.docker_bind = args.tests = args.wheel = True

    if not any([args.license, args.lockfile, args.docker_bind, args.tests, args.wheel]):
        parser.print_help()
        raise SystemExit(1)

    os.chdir(ROOT)
    ok = True

    if args.license:
        add_license()
    if args.lockfile:
        add_lockfile()
    if args.docker_bind:
        fix_docker_bind()
    if args.tests:
        ok = ok and run_tests()
    if args.wheel:
        ok = ok and build_and_verify_wheel()

    print("---")
    if ok:
        log("All requested checks passed")
    else:
        log("One or more checks failed")
        raise SystemExit(1)


if __name__ == "__main__":
    main()
